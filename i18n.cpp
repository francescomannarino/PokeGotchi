void loadLang() {
  Preferences p;
  p.begin(SAVE_NS_PET, true);  // sola lettura
  uint8_t v = p.getUChar("lang", gLangDefault);
  p.end();
  gLang = (v < LANG_COUNT) ? (Lang)v : gLangDefault;
}

void setLang(Lang l) {
  if (l >= LANG_COUNT) return;
  gLang = l;
  Preferences p;
  p.begin(SAVE_NS_PET, false);
  p.putUChar("lang", (uint8_t)l);
  p.end();
}
